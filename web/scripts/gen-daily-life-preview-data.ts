// Generates video-composition/daily-life-preview-data.generated.ts from the
// real parsed `daily_life` content (docs/content/rchop.md) plus the cached
// R-CHOP TTS word timestamps (web/.demo-cache/.../sections/daily_life/) —
// real per-topic reveal timing, not evenly-spaced stand-in beats
// (docs/references/daily_life_motion_spec.md, §5 path B: no closer, so no
// call_team_if data is generated here). Studio's Root.tsx bundle runs in the
// browser (no node:fs), so this is precomputed here rather than parsed live
// in the composition. Re-run after any daily_life content edit or after the
// R-CHOP demo cache is regenerated.
// Run: npm run gen:daily-life-preview

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadRegimenContent } from "../lib/content";
import { matchTimestamps } from "../lib/video/narration";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const content = loadRegimenContent("rchop");
const dailyLife = content.entries.filter((e) => e.sectionId === "daily_life");

const topics = dailyLife.filter((e) => e.name);
if (topics.length === 0) throw new Error("no daily_life sub-topics found");

// Cached R-CHOP TTS output for this exact section (same regimen/filter combo
// already cached — no TTS API call here, just reading the cache file).
const metaPath = path.join(
  __dirname,
  "..",
  ".demo-cache",
  "626258c5f2dfe3ebcf7003d3fa73337254e702d4569ce8bf5797d2eaceb7601f",
  "sections",
  "daily_life",
  "meta.json",
);
const meta = JSON.parse(readFileSync(metaPath, "utf-8")) as {
  chunks: { entryId: string; text: string }[];
  words: { word: string; startSeconds: number }[];
};

// One chunk per sub-topic (entryId "daily_life.<slug>"), plus one leading
// chunk for the section's own intro narration ("daily_life") — same order
// as `topics` above (verified against docs/content/rchop.md: Exercise,
// Driving, Intimacy, Helpful routines, same order as the cache's chunks).
const topicChunks = meta.chunks.filter((c) => c.entryId !== "daily_life");
if (topicChunks.length !== topics.length) {
  throw new Error(
    `daily_life topic count (${topics.length}) doesn't match cached TTS chunk count (${topicChunks.length}) — content and cache have drifted; re-check order/regenerate cache.`,
  );
}

// Reuse the existing anchor-matching pattern (align.ts / narration.ts's
// applyTimepoints, same mechanism overview's drug-tag reveals use): a
// forward-scanning 3-word (falling back to 2/1-word) anchor match against
// the real word-timestamp array, one anchor per topic in narration order.
const ANCHOR_WORDS = 3;
const anchors = topicChunks.map((c) => c.text.split(/\s+/).filter(Boolean).slice(0, ANCHOR_WORDS).join(" "));
const matches = matchTimestamps(anchors, meta.words);

const revealSeconds = matches.map((m, i) => {
  if (m == null) throw new Error(`No anchor match for daily_life topic "${topics[i]!.name}" (anchor "${anchors[i]}")`);
  return m;
});

const out = `// Auto-generated by \`npm run gen:daily-life-preview\` from the real parsed
// daily_life content (docs/content/rchop.md) and the cached R-CHOP TTS word
// timestamps — do not hand-edit; re-run the script after a content or cache
// change. Studio-preview data only (see video-composition/DailyLifeCurve.tsx)
// — not wired into the real narration pipeline yet. §5 path B: no closer, so
// no call_team_if data here.

export interface DailyLifePreviewTopic {
  label: string;
  revealSeconds: number;
}

export const DAILY_LIFE_PREVIEW_TOPICS: DailyLifePreviewTopic[] = ${JSON.stringify(
  topics.map((t, i) => ({ label: t.name!, revealSeconds: revealSeconds[i] })),
  null,
  2,
)};
`;

const outPath = path.join(__dirname, "..", "video-composition", "daily-life-preview-data.generated.ts");
writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${topics.length} topics)`);
